/**
 * Extract a plain string from a v3 description/content field that may be
 * either a string (v2) or an object `{ plain, html, markdown }` (v3).
 */
function normalizeArenaText(val: any): string {
  if (val == null) return "";
  if (typeof val === "string") return val;
  if (typeof val === "object") return val.plain ?? val.markdown ?? "";
  return String(val);
}

/**
 * Normalize a v3 REST block/item into the RawArenaChannelItem shape
 * expected by the rest of the codebase (v2 field names).
 *
 * Key v3 differences handled:
 *  - `type` / `base_type` instead of `class` / `base_class`
 *  - `description` and `content` can be objects `{plain, html, markdown}`
 *  - `image.small.src` instead of `image.thumb.url`
 *  - `image.medium.src` instead of `image.display.url`
 *  - `image.src` instead of `image.original.url`
 *  - `connection.connected_at` / `connection.connected_by` instead of
 *    top-level `connected_at` / `connected_by_user_*`
 *  - `user` shape has `avatar` instead of `avatar_image`
 */
function normalizeV3Block(raw: any): RawArenaChannelItem {
  // If it already has `class`, it's already v2 (e.g. from GraphQL mapper)
  if (raw.class && raw.base_class) return raw as RawArenaChannelItem;

  const arenaClass: ArenaClass =
    raw.class ?? raw.type ?? raw.__typename ?? "Block";
  const baseClass = raw.base_class ?? raw.base_type ?? "Block";

  // Normalize image field from v3 shape to v2 shape
  let image = raw.image;
  if (image && !image.display) {
    image = {
      ...image,
      content_type: image.content_type ?? "image/jpeg",
      display: { url: image.medium?.src ?? image.src ?? image.large?.src ?? "" },
      square: { url: image.square?.src ?? image.small?.src ?? "" },
      thumb: { url: image.small?.src ?? image.square?.src ?? "" },
      original: { url: image.src ?? image.large?.src ?? "" },
    };
  }

  // Normalize connection info
  const connection = raw.connection;
  const connectedAt =
    raw.connected_at ?? connection?.connected_at ?? "";
  const connectedByUserId =
    raw.connected_by_user_id ??
    connection?.connected_by?.id?.toString() ??
    "";
  const connectedByUserSlug =
    raw.connected_by_user_slug ??
    connection?.connected_by?.slug ??
    "";

  // Normalize user avatar
  const user = raw.user ? {
    ...raw.user,
    avatar_image: raw.user.avatar_image ?? {
      thumb: raw.user.avatar ?? "",
      display: raw.user.avatar ?? "",
    },
  } : raw.user;

  return {
    ...raw,
    id: raw.id?.toString?.() ?? raw.id,
    class: arenaClass,
    base_class: baseClass,
    description: normalizeArenaText(raw.description),
    content: arenaClass === "Text"
      ? normalizeArenaText(raw.content)
      : raw.content,
    image: image ?? null,
    connected_at: connectedAt,
    connected_by_user_id: connectedByUserId,
    connected_by_user_slug: connectedByUserSlug,
    user,
  } as RawArenaChannelItem;
}

/**
 * Normalize a v3 channel response to ArenaChannelInfo shape.
 * Handles single-channel endpoints like /v3/channels/{slug}.
 */
function normalizeV3Channel(raw: any): ArenaChannelInfo {
  const description = normalizeArenaText(raw.description);
  return {
    ...raw,
    status: raw.status ?? raw.visibility ?? "closed",
    length: raw.length ?? raw.counts?.blocks ?? 0,
    metadata: { description, ...(raw.metadata ?? {}) },
    owner: raw.owner ? {
      ...raw.owner,
      avatar_image: raw.owner.avatar_image ?? {
        thumb: raw.owner.avatar ?? "",
        display: raw.owner.avatar ?? "",
      },
    } : raw.owner,
    added_to_at: raw.added_to_at ?? raw.updated_at,
    contents: raw.contents ?? [],
  } as ArenaChannelInfo;
}

/**
 * Extract the contents/data array from a v3 response that may use
 * either `contents` (v2) or `data` (v3).
 */
function getContentsFromResponse(respBody: any): any[] {
  return respBody.contents ?? respBody.data ?? [];
}

function maybeParseChannelIdentifierFromUrl(maybeChannelUrl: string): string {
  if (ArenaChannelRegex.test(maybeChannelUrl)) {
    return maybeChannelUrl.match(ArenaChannelRegex)![1];
  }

  return maybeChannelUrl;
}

export function transformChannelUrlToApiUrl(url: string): string {
  const maybeChannelUrl = url.trim();
  if (maybeChannelUrl.startsWith(ArenaChannelsApi)) {
    return maybeChannelUrl;
  }

  const channel = maybeParseChannelIdentifierFromUrl(maybeChannelUrl);
  return `${ArenaChannelsApi}/${channel}`;
}

function escapeArenaStrings(str?: string): string | undefined {
  if (!str) {
    return str;
  }
  return str.replaceAll("&amp;", "&");
}

export async function getChannelThumb(
  channelIdOrUrl: string,
  { accessToken }: { accessToken?: string | null } = {},
): Promise<RawArenaChannelItem[]> {
  const channelId = maybeParseChannelIdentifierFromUrl(channelIdOrUrl);
  // v3 has no /thumb endpoint; fetch first page of contents instead
  const url = `${ArenaChannelsApi}/${channelId}/contents?per=20`;
  const resp = await fetch(url, {
    headers: {
      ...(accessToken ? { Authorization: `Bearer ${accessToken}` } : {}),
    },
  });
  if (!resp.ok) {
    throw new Error(`${resp.status}: failed to fetch channel thumb`);
  }
  const respBody = await resp.json();
  const items = getContentsFromResponse(respBody)
    .map(normalizeV3Block)
    .filter((c) => c.base_class === "Block" && c.class !== "Block");
  return items;
}

function mapListChannelItemsResponseToItems(
  result: ListChannelBlocksResult,
): RawArenaChannelItem[] {
  return result.data.channel.blokks.map<RawArenaChannelItem>((block) => {
    const { user, connection_to, __typename, url, id, ...rest } = block;
    let blockInfo = {};
    switch (__typename) {
      case "Link":
        blockInfo = {
          content: block.image_url,
        };
        break;
      case "Image":
        blockInfo = {
          image: {
            content_type: block.content_type,
            display: { url: block.display },
          },
        };
        break;
      case "Embed":
        blockInfo = {
          embed: {
            url: block.embed_url,
          },
        };
        break;
      case "Attachment":
        blockInfo = {
          attachment: {
            content_type: block.content_type,
            url: block.file_url,
          },
        };
        break;
    }
    return {
      ...rest,
      id: id.toString(),
      connected_at: connection_to.connected_at,
      connected_by_user_id: connection_to.user.id.toString(),
      connected_by_user_slug: connection_to.user.slug,
      class: __typename,
      base_class: "Block",
      // @ts-ignore
      user: user as RawArenaUser,
      url: `https://are.na/${url}`,
      ...blockInfo,
    } as RawArenaChannelItem;
  });
}

const DefaultBlockPer = 30;
export async function getChannelItemsPaginated(
  channelId: string,
  {
    accessToken,
    page = 1,
    per = DefaultBlockPer,
  }: { accessToken?: string | null; page?: number; per?: number } = {},
): Promise<RawArenaChannelItem[]> {
  const baseQuery = listChannelBlocksQuery({ channelId, per, page });
  console.log(
    `[Arena GraphQL] Fetching channel ${channelId} page=${page} per=${per}`,
  );
  const resp = await fetch(ArenaGraphqlApi, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${accessToken}`,
      "Content-Type": "application/json",
      "X-APP-TOKEN": ArenaGraphqlKey,
    },
    body: JSON.stringify({
      query: baseQuery,
    }),
  });
  const respBody = await resp.json();
  if (!resp.ok || respBody.errors) {
    console.error(
      `[Arena GraphQL] Error fetching channel ${channelId}:`,
      resp.status,
      JSON.stringify(respBody.errors ?? respBody),
    );
    if (respBody.errors) {
      throw new Error(
        `GraphQL error: ${respBody.errors.map((e: any) => e.message).join(", ")}`,
      );
    }
  }
  if (!respBody.data?.channel?.blokks) {
    console.error(
      `[Arena GraphQL] Unexpected response shape for channel ${channelId}:`,
      JSON.stringify(respBody).slice(0, 500),
    );
    return [];
  }
  console.log(
    `[Arena GraphQL] Got ${respBody.data.channel.blokks.length} blocks for channel ${channelId}`,
  );
  let contents: RawArenaChannelItem[] =
    mapListChannelItemsResponseToItems(respBody);
  return contents;
}

export async function getChannelItems(
  channelId: string,
  {
    accessToken,
    lastSyncedInfo,
  }: { accessToken?: string | null; lastSyncedInfo?: LastSyncedInfo | null },
) {
  console.log(
    "Fetching items for channel",
    channelId,
    ". Looking for items after ",
    lastSyncedInfo?.lastSyncedBlockCreatedAt,
  );
  let fetchedItems: RawArenaChannelItem[] = [];
  let newItemsFound = lastSyncedInfo ? false : true;
  const lastSyncedBlockCreatedAt = lastSyncedInfo?.lastSyncedBlockCreatedAt;
  let numItemsFetched = 0;
  let page = 1;
  const per = DefaultBlockPer;
  const baseQuery = listChannelBlocksQuery({ channelId, page });

  function nextQueryFromResponse(
    currentPage: number,
    per: number,
    items: RawArenaChannelItem[],
  ) {
    if (items.length === per) {
      return listChannelBlocksQuery({ channelId, page: currentPage + 1 });
    }
  }
  try {
    let nextQuery: string | undefined = baseQuery;
    while (nextQuery) {
      let contents = await getChannelItemsPaginated(channelId, {
        page,
        per,
        accessToken,
      });
      numItemsFetched += contents.length;
      const stopIdx = lastSyncedBlockCreatedAt
        ? contents.findIndex(
            (c) =>
              new Date(c.connected_at).getTime() <
              new Date(lastSyncedBlockCreatedAt).getTime(),
          )
        : null;
      console.log("stopidx", stopIdx, lastSyncedBlockCreatedAt);

      if (stopIdx && stopIdx > -1) {
        contents = contents.slice(0, stopIdx);
      }
      fetchedItems.push(...contents);

      if (stopIdx !== null && stopIdx > -1) {
        // we finished fetching all the items we needed
        break;
      }

      nextQuery = nextQueryFromResponse(page, per, contents);
      page++;
    }
  } catch (e) {
    logError(e);
    throw e;
  }
  console.log(
    `Fetched ${numItemsFetched} items. Returned ${fetchedItems.length} items.`,
  );
  return fetchedItems;
}

