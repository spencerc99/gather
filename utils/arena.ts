export function apiUrl(
  baseUrl: string,
  path: string,
  params?: Record<string, any>,
): string {
  const url = `${baseUrl}${path}`;
  return withQueryParams(url, params || {});
}

export function nextUrlFromResponse(
  baseUrl: string,
  path: string,
  params: Record<string, any>,
  response: any,
): string | undefined {
  // Handle v3 meta.has_more_pages pagination
  if (response.meta?.has_more_pages) {
    const currPage =
      response.meta.current_page || response.page || response.current_page || 1;
    return apiUrl(baseUrl, path, { ...params, page: currPage + 1 });
  }
  // Fallback to v2 pagination
  const { page, length, per, current_page } = response;
  let currPage = page || current_page;
  if (currPage && per && length && currPage * per < length) {
    return apiUrl(baseUrl, path, { ...params, page: currPage + 1 });
  }
}

export function nextUrlFromArenaContentsResponse(
  baseUrl: string,
  path: string,
  params: Record<string, any>,
  response: any,
  perPage: number = 20,
): string | undefined {
  // v3 uses meta.has_more_pages
  if (response.meta?.has_more_pages) {
    const currPage = response.meta.current_page || Number(params.page) || 1;
    return apiUrl(baseUrl, path, { ...params, page: currPage + 1 });
  }
  // v2 fallback: check if contents array is full page
  const items = getContentsFromResponse(response);
  if (items.length === perPage) {
    return apiUrl(baseUrl, path, {
      ...params,
      page: (Number(params.page) || 1) + 1,
    });
  }
}

